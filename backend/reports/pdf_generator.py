def create_revenue_chart(historical, predictions):

    drawing = Drawing(
        165 * mm,
        75 * mm,
    )

    chart = VerticalBarChart()

    chart.x = 12 * mm
    chart.y = 12 * mm
    chart.height = 50 * mm
    chart.width = 140 * mm

    chart.valueAxis.valueMin = 0

    all_values = historical + predictions

    if all_values:
        chart.valueAxis.valueMax = max(all_values) * 1.2

    chart.valueAxis.valueStep = (
        max(all_values) / 5
        if all_values
        else 1
    )

    chart.categoryAxis.labels.fontName = "Helvetica"
    chart.categoryAxis.labels.fontSize = 7

    labels = []

    for index in range(len(historical)):
        labels.append(f"P{index + 1}")

    for index in range(len(predictions)):
        labels.append(f"F{index + 1}")

    chart.categoryAxis.categoryNames = labels

    # ReportLab requires series data.
    # Historical bars and forecast bars are represented
    # in separate series.

    historical_series = []

    forecast_series = []

    for index in range(len(all_values)):

        if index < len(historical):
            historical_series.append(
                historical[index]
            )
            forecast_series.append(0)

        else:
            historical_series.append(0)
            forecast_series.append(
                predictions[
                    index - len(historical)
                ]
            )

    chart.data = [
        historical_series,
        forecast_series,
    ]

    chart.bars[0].fillColor = colors.HexColor(
        "#374151"
    )

    chart.bars[1].fillColor = colors.HexColor(
        "#60a5fa"
    )

    chart.valueAxis.labels.fontName = "Helvetica"
    chart.valueAxis.labels.fontSize = 7

    drawing.add(chart)

    return drawing


