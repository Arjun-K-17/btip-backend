def draw_header_footer(canvas, doc):
    canvas.saveState()

    width, height = A4

    # Header line
    canvas.setStrokeColor(colors.HexColor("#d1d5db"))
    canvas.line(
        18 * mm,
        height - 15 * mm,
        width - 18 * mm,
        height - 15 * mm,
    )

    # Header text
    canvas.setFont("Helvetica-Bold", 9)
    canvas.setFillColor(colors.HexColor("#1f2937"))
    canvas.drawString(
        18 * mm,
        height - 11 * mm,
        "BTIP"
    )

    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#6b7280"))
    canvas.drawRightString(
        width - 18 * mm,
        height - 11 * mm,
        "Business Turnaround Intelligence Platform"
    )

    # Footer line
    canvas.setStrokeColor(colors.HexColor("#d1d5db"))
    canvas.line(
        18 * mm,
        14 * mm,
        width - 18 * mm,
        14 * mm,
    )

    # Footer
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.HexColor("#6b7280"))

    canvas.drawString(
        18 * mm,
        9 * mm,
        "Generated by BTIP"
    )

    canvas.drawRightString(
        width - 18 * mm,
        9 * mm,
        f"Page {doc.page}"
    )

    canvas.restoreState()


