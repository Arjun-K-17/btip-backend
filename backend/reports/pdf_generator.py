def currency(value):
    if value is None:
        return "N/A"

    try:
        return f"Rs. {float(value):,.0f}"
    except (TypeError, ValueError):
        return "N/A"


def number(value, decimals=2):
    if value is None:
        return "N/A"

    try:
        return f"{float(value):.{decimals}f}"
    except (TypeError, ValueError):
        return "N/A"


def percentage(value):
    if value is None:
        return "N/A"

    try:
        return f"{float(value):.2f}%"
    except (TypeError, ValueError):
        return "N/A"


def safe_text(value):
    if value is None:
        return "N/A"

    return str(value)


